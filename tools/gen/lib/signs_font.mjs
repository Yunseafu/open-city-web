/** Look up a glyph by character. Unknown characters become an outlined box. */
export function glyph(ch) {
  const up = ch.toUpperCase();
  if (LATIN[up]) return LATIN[up];
  if (KANA[ch]) return { w: 6, s: KANA[ch] };
  if (KANJI[ch]) return { w: 6, s: KANJI[ch] };
  return { w: 4, s: [R(0.4, 0.4, 3.6, 5.6)] };
}

/** Advance (grid units) between glyphs. */
export const SPACING = 1.7;

export function textUnits(text) {
  let u = 0;
  for (const ch of text) u += glyph(ch).w + SPACING;
  return Math.max(0, u - SPACING);
}

