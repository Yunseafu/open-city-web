// Stroke font and icon shapes for neon lettering (used by signs.mjs).
//
// A glyph is { w, s, f }: advance width `w` in grid units, `s` = polylines [[x,y],...] drawn as
// neon tube strokes, `f` = filled rectangles [x0,y0,x1,y1]. Coordinates are in a grid whose
// height is 6 units (y up, baseline 0): Latin letters are ~4 wide, kana / kanji-like glyphs 6 wide.
// Strokes cost 2 triangles per segment, so shapes use as few points as they can.

const R = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1], [x0, y0]];
const OCT = (cx, cy, rx, ry) => {
  const o = [];
  for (let i = 0; i <= 8; i++) {
    const a = (i / 8) * Math.PI * 2 + Math.PI / 8;
    o.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return o;
};

