function bbox(strokes) {
  let x0 = Infinity;
  let x1 = -Infinity;
  for (const s of strokes) for (const [x] of s) (x0 = Math.min(x0, x), (x1 = Math.max(x1, x)));
  return [x0, x1];
}

/** Strokes of one Latin glyph in glyph units (4 x 6), or null. */
export function glyph(ch) {
  return G[ch.toUpperCase()] ?? null;
}

/**
 * Lay out text as strokes in glyph units: { strokes, width, height }. Proportional spacing from glyph bounding boxes.
 * opts: { spacing = 1.2 (gap between glyphs, glyph units) }
 */
export function layoutText(text, { spacing = 1.2 } = {}) {
  const strokes = [];
  let cx = 0;
  for (const ch of text) {
    if (ch === " ") {
      cx += 2.2;
      continue;
    }
    const g = glyph(ch);
    if (!g) continue;
    const [x0, x1] = bbox(g);
    const w = Math.max(x1 - x0, 1.2);
    for (const s of g) strokes.push(s.map(([x, y]) => [x - x0 + cx, y]));
    cx += w + spacing;
  }
  return { strokes, width: Math.max(0, cx - spacing), height: GLYPH_H };
}

/** Text strokes in pixels. `size` is the text height. align: "left" | "center" | "right" about x. */
export function textStrokes(text, x, y, size, { spacing = 1.2, align = "left", slant = 0 } = {}) {
  const lay = layoutText(text, { spacing });
  const s = size / GLYPH_H;
  const w = lay.width * s;
  const ox = align === "center" ? x - w / 2 : align === "right" ? x - w : x;
  return lay.strokes.map((p) => p.map(([gx, gy]) => [ox + gx * s + slant * (GLYPH_H - gy) * s, y + gy * s]));
}

export function textWidth(text, size, spacing = 1.2) {
  return layoutText(text, { spacing }).width * (size / GLYPH_H);
}

/** Text fitted into a box (keeps proportions, centred); returns strokes and the chosen text height. */
export function fitText(text, box, { spacing = 1.2, maxSize = Infinity } = {}) {
  const lay = layoutText(text, { spacing });
  const size = Math.min(box.h, (box.w / lay.width) * GLYPH_H, maxSize);
  const w = textWidth(text, size, spacing);
  return { strokes: textStrokes(text, box.x + (box.w - w) / 2, box.y + (box.h - size) / 2, size, { spacing }), size };
}

/** Stroke thickness (px) that looks like a neon tube / bold paint for a given text height. */
export const strokeFor = (size, weight = 0.15) => Math.max(2, size * weight);

/** Draw polylines into a Field (no wrapping, max blend). */
export function drawStrokes(field, strokes, thickness, value = 1, opts = {}) {
  for (const s of strokes) polyline(field, s, thickness, value, { mode: "max", wrap: false, ...opts });
}

export function drawText(field, text, x, y, size, value = 1, { thickness, ...opts } = {}) {
  drawStrokes(field, textStrokes(text, x, y, size, opts), thickness ?? strokeFor(size), value);
}

// ---------------------------------------------------------------- placement helpers
/** Map strokes from the unit box (0..1) into a pixel rect. */
export function place(strokes, x, y, w, h) {
  return strokes.map((s) => s.map(([u, v]) => [x + u * w, y + v * h]));
}

/** Place unit-box glyphs side by side inside a rect, `gap` as a fraction of one glyph width. */
export function glyphRow(glyphs, x, y, w, h, gap = 0.12) {
  const n = glyphs.length;
  const gw = w / (n + (n - 1) * gap);
  return glyphs.flatMap((g, i) => place(g, x + i * gw * (1 + gap), y, gw, h));
}

export function glyphColumn(glyphs, x, y, w, h, gap = 0.12) {
  const n = glyphs.length;
  const gh = h / (n + (n - 1) * gap);
  return glyphs.flatMap((g, i) => place(g, x, y + i * gh * (1 + gap), w, gh));
}

